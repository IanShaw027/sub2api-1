// Package cloudip classifies addresses that belong to cloud, hosting, or
// datacenter networks. It is intended for registration-time checks only —
// API Key traffic from the same networks is a supported deployment pattern
// (keys hosted on a user's cloud VM).
package cloudip

import (
	"net/netip"
	"strings"
	"sync"
)

var (
	once     sync.Once
	prefixes []netip.Prefix
)

// IsDatacenter reports whether ip belongs to a well-known cloud, hosting, or
// datacenter range. Invalid or empty input is not treated as datacenter.
func IsDatacenter(ip string) bool {
	parsed, err := netip.ParseAddr(strings.TrimSpace(ip))
	if err != nil {
		return false
	}
	if parsed.Is4In6() {
		parsed = parsed.Unmap()
	}
	for _, prefix := range datacenterPrefixes() {
		if prefix.Contains(parsed) {
			return true
		}
	}
	return false
}

func datacenterPrefixes() []netip.Prefix {
	once.Do(func() {
		prefixes = parsePrefixes(datacenterCIDRs)
	})
	return prefixes
}

func parsePrefixes(cidrs []string) []netip.Prefix {
	out := make([]netip.Prefix, 0, len(cidrs))
	for _, cidr := range cidrs {
		prefix, err := netip.ParsePrefix(cidr)
		if err != nil {
			continue
		}
		out = append(out, prefix.Masked())
	}
	return out
}

